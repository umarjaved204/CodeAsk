"""Decide which repo files to ingest: a category for each kept file, a reason for each skip.

Embedding is the scarce resource (Voyage: 3 requests/min), so every embedded token should be
something a user might ask about. Generated, minified and data-like files never are.
Only scan_repo touches the filesystem; the rules are pure functions over paths and text.
"""

from __future__ import annotations

import os
import re
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from codeask import config

SOURCE_EXT = {".py", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".mts", ".cts", ".tsx", ".go", ".rs",
              ".java", ".rb", ".c", ".h", ".cpp", ".cs", ".php", ".swift", ".kt", ".vue",
              ".svelte", ".sql", ".sh"}
DOC_EXT = {".md", ".rst"}
SKIP_DIRS = {".git", ".github", "node_modules", "dist", "build", "vendor", ".venv", "venv",
             "__pycache__", ".next", "out", "coverage", "target"}
DOC_SKIP_PREFIXES = ("changes", "changelog", "license", "history")
TEST_DIRS = {"test", "tests", "__tests__", "spec"}

# Deliberately not a bare "generated": that word appears in ordinary docstrings.
GENERATED_MARKER = re.compile(
    r"@generated|do not edit|auto-?generated|generated by|code generated", re.IGNORECASE)
GENERATED_NAME = re.compile(r"\.gen\.|_pb2\.py$|\.pb\.go$|\.d\.ts$")


@dataclass
class RepoFile:
    path: str  # repo-relative, forward slashes
    category: str  # "source", "test" or "doc"
    text: str  # decoded, BOM stripped, CRLF -> LF


@dataclass
class ScanResult:
    files: list[RepoFile] = field(default_factory=list)
    skipped: list[tuple[str, str]] = field(default_factory=list)  # (path, reason)
    excluded: Counter = field(default_factory=Counter)  # category not requested -> file count
    ignored: int = 0  # file types we never ingest (images, JSON, lockfiles, ...)


def category(rel: PurePosixPath) -> str | None:
    """'source', 'test' or 'doc'; None for file types we never ingest."""
    name = rel.name.lower()
    suffix = rel.suffix.lower()
    if suffix in DOC_EXT:
        return None if name.startswith(DOC_SKIP_PREFIXES) else "doc"
    if suffix not in SOURCE_EXT:
        return None
    dirs = {part.lower() for part in rel.parts[:-1]}
    is_test = (
        bool(dirs & TEST_DIRS)
        or name.startswith("test_") or name.endswith("_test.py") or name == "conftest.py"
        or ".test." in name or ".spec." in name
    )
    return "test" if is_test else "source"


def is_root_readme(rel: PurePosixPath) -> bool:
    return len(rel.parts) == 1 and rel.stem.lower() == "readme"


def path_skip_reason(rel: PurePosixPath) -> str | None:
    """Skip rules that need only the path."""
    dirs = [part.lower() for part in rel.parts[:-1]]
    name = rel.name.lower()
    if "migrations" in dirs:
        return "path rule: migrations/"
    if any(a == "alembic" and b == "versions" for a, b in zip(dirs, dirs[1:])):
        return "path rule: alembic/versions/"
    # A fixtures/ directory holds test data; a fixtures.py file can be real code (TableTalk).
    if "fixtures" in dirs:
        return "path rule: fixtures/"
    if name == "conf.py" and dirs and dirs[-1] in {"docs", "doc"}:
        return "path rule: docs/conf.py"
    if GENERATED_NAME.search(name):
        return "generated file name"
    if ".min." in name:
        return "minified file name"
    return None


def decode(raw: bytes) -> str | None:
    """Strict UTF-8, BOM stripped, CRLF -> LF; None if not UTF-8.

    Normalizing makes hashes identical on Windows and Linux. Only CRLF is converted: a lone
    CR is left alone, and callers must split lines on "\\n" only (never str.splitlines(),
    which also splits on \\x0c, \\u2028 and others, putting line numbers out of step with
    tree-sitter and GitHub).
    """
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        return None
    return text.replace("\r\n", "\n")


def content_skip_reason(text: str, cat: str) -> str | None:
    """Skip rules that need the decoded text."""
    if not text.strip():
        return "empty"
    head = "\n".join(text.split("\n", config.MARKER_LINES)[:config.MARKER_LINES])
    if GENERATED_MARKER.search(head):
        return "generated marker"
    if cat == "doc":
        return None  # long lines are normal in markdown (unwrapped paragraphs)
    lines = [line for line in text.split("\n") if line.strip()]
    longest = max(len(line) for line in lines)
    if longest > config.MAX_LINE_CHARS:
        return f"data-like: line of {longest} chars"
    average = sum(len(line) for line in lines) / len(lines)
    if average > config.MAX_AVG_LINE_CHARS:
        return f"data-like: average line {average:.0f} chars"
    return None


def scan_repo(root: Path, include_tests: bool = False, include_docs: bool = False) -> ScanResult:
    """Walk a cloned repo in a deterministic order and apply every rule."""
    result = ScanResult()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)  # prune and order
        for filename in sorted(filenames):
            full = Path(dirpath) / filename
            rel = PurePosixPath(full.relative_to(root).as_posix())
            cat = category(rel)
            if cat is None:
                result.ignored += 1
                continue
            wanted = (cat == "source"
                      or (cat == "test" and include_tests)
                      or (cat == "doc" and (include_docs or is_root_readme(rel))))
            if not wanted:
                result.excluded[cat] += 1
                continue
            text = None
            # A symlink can point outside the repo (e.g. at ~/.env); never follow it.
            if full.is_symlink():
                reason = "symlink"
            else:
                reason = path_skip_reason(rel)
            if reason is None and full.stat().st_size > config.MAX_FILE_BYTES:
                reason = f"over {config.MAX_FILE_BYTES // 1000} KB"
            if reason is None:
                text = decode(full.read_bytes())
                reason = "not UTF-8" if text is None else content_skip_reason(text, cat)
            if reason:
                result.skipped.append((str(rel), reason))
            else:
                result.files.append(RepoFile(str(rel), cat, text))
    return result
