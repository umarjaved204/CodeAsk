import os
from pathlib import PurePosixPath as P

import pytest

from codeask import config
from codeask.filters import (category, content_skip_reason, decode, is_root_readme,
                             path_skip_reason, scan_repo)


# ---------- category ----------
@pytest.mark.parametrize("path, expected", [
    ("src/app/signer.py", "source"),
    ("web/src/card.tsx", "source"),
    ("lib/util.mjs", "source"),
    ("tests/test_signer.py", "test"),
    ("src/signer_test.py", "test"),
    ("conftest.py", "test"),
    ("web/__tests__/card.js", "test"),
    ("web/card.spec.ts", "test"),
    ("web/card.test.tsx", "test"),
    ("README.md", "doc"),
    ("docs/guide.rst", "doc"),
    ("CHANGELOG.md", None),
    ("LICENSE.md", None),
    ("package.json", None),
    ("logo.png", None),
])
def test_category(path, expected):
    assert category(P(path)) == expected


def test_root_readme_only():
    assert is_root_readme(P("README.md"))
    assert is_root_readme(P("readme.rst"))
    assert not is_root_readme(P("docs/README.md"))


